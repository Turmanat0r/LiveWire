// The app's database types, made by Supabase's own generator from the
// database the migrations build, and compared with the committed file. On a
// PC the database is the stand-in; in CI it is a real Supabase, so the
// stand-in cannot drift from Supabase without this failing.
//
// After changing a migration, `npm run db:types` rewrites the file.
import { fileURLToPath } from 'node:url';
import { introspect } from '@supabase/postgrest-typegen/introspection';
import { generateTypescript, sortGeneratorMetadata } from '@supabase/postgrest-typegen/generation';
import { format, resolveConfig } from 'prettier';
import { afterAll, beforeAll, expect, it } from 'vitest';
import { TestDb } from './harness';

const TYPES_FILE = fileURLToPath(new URL('../../src/data/database.types.ts', import.meta.url));

const HEADER = `// GENERATED by \`npm run db:types\` - do not edit by hand.
//
// Supabase's type generator, run against the database that
// supabase/migrations builds. tests/db/types.test.ts fails while this file is
// out of date.

`;

let db: TestDb;
beforeAll(async () => {
  db = await TestDb.open();
});
afterAll(async () => {
  await db.close();
});

it('the generated database types match the migrations', async () => {
  const metadata = await introspect(
    { query: async (sql) => ({ rows: await db.admin(sql) }) },
    { includedSchemas: ['public'] },
  );
  const code = await generateTypescript(sortGeneratorMetadata(metadata), {
    detectOneToOneRelationships: true,
    postgrestVersion: '14',
    format: (raw) => Promise.resolve(raw),
  });
  const config = await resolveConfig(TYPES_FILE);
  const file = await format(HEADER + code, { ...config, filepath: TYPES_FILE });
  await expect(file).toMatchFileSnapshot(TYPES_FILE);
});
